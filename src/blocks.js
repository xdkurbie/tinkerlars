function sections(ws, gen) {
  gen.init(ws);
  let setup = '', loop = '';
  for (const top of ws.getTopBlocks(true)) {
    if (top.type === 'arduino_setup') setup += gen.blockToCode(top, true);
    else if (top.type === 'arduino_loop') loop += gen.blockToCode(top, true);
  }
  return { setup, loop };
}
export function toArduino(ws) {
  const { setup, loop } = sections(ws, arduinoGen);
  return `// Generated by TinkerLARS\nvoid setup() {\n${setup}}\n\nvoid loop() {\n${loop}}\n`;
}
export function toSimJS(ws) { return sections(ws, jsGen); }

/** Run generated program against an api. Returns stop(). */
export function runProgram(ws, api) {
  const { setup, loop } = toSimJS(ws);
  const AsyncFn = Object.getPrototypeOf(async function () {}).constructor;
  const fSetup = new AsyncFn('api', setup), fLoop = new AsyncFn('api', loop);
  let running = true;
  const guard = { ...api, delay: async (ms) => { if (!running) throw new Error('stopped'); await api.delay(ms); if (!running) throw new Error('stopped'); }, tick: async () => { await api.delay(0); if (!running) throw new Error('stopped'); } };
  const done = (async () => {
    try { await fSetup(guard); while (running) { await fLoop(guard); await guard.tick(); } } catch (e) { if (e.message !== 'stopped') throw e; }
  })();
  return { stop: () => { running = false; }, done };
}

