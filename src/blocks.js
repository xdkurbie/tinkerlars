  delay_ms: (b) => `delay(${b.getFieldValue('MS')});\n`,
  repeat_times: (b, g) => `for (int i = 0; i < ${b.getFieldValue('N')}; i++) {\n${g.statementToCode(b, 'DO')}}\n`,
  if_else: (b, g) => `if (${g.valueToCode(b, 'COND', 0) || 'false'}) {\n${g.statementToCode(b, 'THEN')}} else {\n${g.statementToCode(b, 'ELSE')}}\n`,
  not: (b, g) => [`!(${g.valueToCode(b, 'X', 0) || 'false'})`, 0],
